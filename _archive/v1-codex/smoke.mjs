import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', error => errors.push(`pageerror:${error.message}`));
page.on('console', message => { if (message.type() === 'error') errors.push(`console:${message.text()}`); });
await page.goto('http://127.0.0.1:4173/');
console.log('home', await page.title(), (await page.locator('h1').first().innerText()).slice(0, 20));
await page.getByRole('button', { name: /从一个专辑开始/ }).click();
await page.getByRole('button', { name: /识别内容/ }).click();
console.log('studio', await page.locator('.recognised').innerText());
await page.locator('[data-format="gallery"]').last().click();
await page.locator('[data-action="create"]').click();
await page.waitForTimeout(600);
console.log('experience', await page.locator('.gallery-title h1').innerText(), await page.locator('.wall-piece').count());
await page.locator('[data-action="share"]').click();
console.log('share', await page.locator('.modal-card h2').innerText());
await page.locator('.modal-close').click();
await page.locator('.wall-piece').first().click();
console.log('artwork', await page.locator('.modal-card h2').innerText());
await page.setViewportSize({ width: 390, height: 844 });
await page.goto('http://127.0.0.1:4173/');
console.log('mobile', (await page.locator('h1').first().innerText()).slice(0, 20));
console.log('errors', errors);
await browser.close();
